# Rscript --vanilla scripts/03_check_source.R /path/to/kdrcc /path/to/check_output
args<-commandArgs(TRUE)
source_dir<-if(length(args))args[1] else file.path("..",enc2utf8("R\u5305\u8d44\u6599"),"kdrcc")
output_dir<-if(length(args)>1L)args[2] else file.path("results","source_check")
source_dir<-normalizePath(source_dir,winslash="/",mustWork=TRUE)
dir.create(output_dir,recursive=TRUE,showWarnings=FALSE)
output_dir<-normalizePath(output_dir,winslash="/",mustWork=TRUE)
original<-getwd();setwd(output_dir)
r<-file.path(R.home("bin"),if(.Platform$OS.type=="windows")"R.exe" else "R")
desc<-read.dcf(file.path(source_dir,"DESCRIPTION"));tar<-paste0(desc[1,"Package"],"_",desc[1,"Version"],".tar.gz")
status<-system2(r,c("CMD","build","--no-build-vignettes",shQuote(source_dir)),stdout="build.log",stderr="build.log")
if(status!=0L)stop("Package build failed; inspect build.log.")
status<-system2(r,c("CMD","check","--no-manual","--no-build-vignettes",shQuote(tar)),stdout="check.log",stderr="check.log")
setwd(original)
if(status!=0L)stop("Package check returned errors; inspect the recorded check output.")
cat("Source check records:",output_dir,"\n")
